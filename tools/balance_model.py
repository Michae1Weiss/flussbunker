#!/usr/bin/env python3
"""Balance model for Flussbunker. Derives numbers from the rules in docs/design/economy.md
and checks them against the threat→answer table in docs/design/enemies.md.

Run:  python3 tools/balance_model.py > docs/balance/README.md
Every constant below is a proposal for balance.rs; the checks at the bottom say whether the
proposal still satisfies the rules. Change a number, rerun, read the checks.
"""

TILE = 48.0  # world units per tile; every range and speed is given in tiles

# --- economy rules (docs/design/economy.md) ----------------------------------
ECONOMY_TARGET = 0.60       # income of a perfect run / cost of everything maxed
BOAT_SHARE = 0.50           # boat ≈ half the defence budget
SELL_REFUND = 0.60
REPAIR_BILL = 0.30          # of the boat's nominal value
WAVE_CLEAR_BONUS = 30
PROLOGUE_BOUNTY = 150       # one flak + savings, or two flak
STARTING_RM = 0

# --- turrets: build, upgrade 1, upgrade 2 -----------------------------------
TURRETS = {
    "flak": dict(cost=(60, 50, 80), range=2.6, damage=9.0, reload=0.35, turn=360.0),
    "8.8":  dict(cost=(120, 100, 150), range=3.6, damage=32.0, reload=1.4, turn=180.0),
    "15cm": dict(cost=(240, 180, 280), range=4.4, damage=100.0, reload=3.0, turn=90.0),
}
# Reference "everything maxed": 8 spots as 3 flak, 3 × 8.8, 2 × 15 cm.
REFERENCE_BUILD = {"flak": 3, "8.8": 3, "15cm": 2}
ARMOUR_FLOOR = 0.10
AP_ARMOUR_FACTOR = 0.5      # 8.8 upgrade 1 halves armour

# --- boat models (docs/design/uboat.md) ---------------------------------------
BOATS = [
    dict(name="VIIA", price=0, nominal=300, unlock=0, hp=130, tubes=4, torpedo=130.0,
         speed=190, dive=1.4),
    dict(name="VIIC", price=500, nominal=800, unlock=4, hp=165, tubes=6, torpedo=150.0,
         speed=195, dive=1.1),
    dict(name="IXC", price=900, nominal=1700, unlock=8, hp=220, tubes=8, torpedo=150.0,
         speed=170, dive=1.8),
]
DECK_GUN = dict(damage=22.0, reload=2.4, range=2.4)
DESTROYER_SHELLING = dict(ranging=3.0, damage=18.0, reload=1.5, range=2.6)
RAM = dict(passive_light=0.05, passive_heavy=0.40, active_light=0.03)  # fraction of boat max HP
TORPEDO_RUN_TILES = 9.0     # must be shorter than the longest straight

# --- enemies (docs/design/enemies.md) ----------------------------------------
# Capital armour is set above any shell's damage: shells bounce (armour floor only).
# That is what makes the monitor torpedo-only and a boat-less run impossible (pillar 1).
ENEMIES = {
    "MTB":       dict(cls="light",   hp=38.0,   armour=0.0,   speed=2.45, bounty=4,  breach=1),
    "Corvette":  dict(cls="medium",  hp=120.0,  armour=3.0,   speed=1.30, bounty=12, breach=2),
    "Landing":   dict(cls="medium",  hp=300.0,  armour=1.0,   speed=0.80, bounty=20, breach=5),
    "Destroyer": dict(cls="heavy",   hp=380.0,  armour=12.0,  speed=1.05, bounty=48, breach=4),
    "Monitor":   dict(cls="capital", hp=1200.0, armour=100.0, speed=0.63, bounty=100, breach=8),
}
# Prologue target: dies to two VIIA torpedoes or ~25 s of deck gun. Bounty = PROLOGUE_BOUNTY.
GOLD_TRANSPORT = dict(cls="medium", hp=200.0, armour=0.0, speed=0.70)
STARTING_INTEGRITY = 20

# --- waves: (kind, count) groups in spawn order; fast before slow -------------
WAVES = [
    ("Reconnaissance",  [("MTB", 6)]),
    ("Wolfpack",        [("MTB", 12)]),
    ("Convoy",          [("MTB", 8), ("Corvette", 4)]),
    ("Destroyer ahead", [("MTB", 4), ("Corvette", 3), ("Destroyer", 1)]),
    ("Under fire",      [("MTB", 10), ("Destroyer", 2)]),
    ("Landing",         [("MTB", 6), ("Corvette", 4), ("Landing", 3)]),
    ("Double blow",     [("MTB", 18), ("Destroyer", 2)]),
    ("Blockade runner", [("MTB", 10), ("Landing", 4), ("Destroyer", 2)]),
    ("Hunter group",    [("Corvette", 6), ("Destroyer", 3)]),
    ("Grand assault",   [("MTB", 20), ("Corvette", 8), ("Landing", 4)]),
    ("Vanguard",        [("MTB", 8), ("Destroyer", 4), ("Landing", 5)]),
    ("The monitor",     [("MTB", 16), ("Destroyer", 4), ("Monitor", 2)]),
]


def maxed(t):
    return sum(TURRETS[t]["cost"])


def hit(damage, armour, ap=False):
    a = armour * (AP_ARMOUR_FACTOR if ap else 1.0)
    return max(damage - a, damage * ARMOUR_FLOOR)


def exposure(range_tiles, speed):
    """Seconds an enemy spends inside a turret's circle when the path crosses its centre."""
    return 2.0 * range_tiles / speed


def main():
    out = []
    p = out.append

    p("# Balance model\n")
    p("Generated by `tools/balance_model.py`. Do not edit by hand; edit the script and rerun.\n")
    p("Rules it must satisfy: `docs/design/economy.md`, `docs/design/enemies.md`.\n")

    # ---- cost of everything -------------------------------------------------
    turret_max = sum(maxed(t) * n for t, n in REFERENCE_BUILD.items())
    boat_max = sum(b["price"] for b in BOATS)
    everything = turret_max + boat_max

    p("## Costs\n")
    p("| Turret | Build | Upgrade 1 | Upgrade 2 | Maxed |")
    p("|---|---|---|---|---|")
    for t, d in TURRETS.items():
        c = d["cost"]
        p(f"| {t} | {c[0]} | {c[1]} | {c[2]} | {maxed(t)} |")
    p("")
    p("| Boat | Price | Nominal value | Repair bill (30 %) | Unlock wave | HP | Tubes | Torpedo dmg |")
    p("|---|---|---|---|---|---|---|---|")
    for b in BOATS:
        p(f"| {b['name']} | {b['price']} | {b['nominal']} | {round(b['nominal'] * REPAIR_BILL)} | "
          f"{b['unlock']} | {b['hp']} | {b['tubes']} | {b['torpedo']:.0f} |")
    p("")
    ref = ", ".join(f"{n} × {t}" for t, n in REFERENCE_BUILD.items())
    p(f"Reference full build ({ref}, all maxed): **{turret_max} RM**. Boat maxed: **{boat_max} RM**. "
      f"Everything: **{everything} RM**.\n")

    # ---- income -------------------------------------------------------------
    p("## Waves and income\n")
    p("| # | Wave | Composition (spawn order) | Kill RM | + bonus | Cumulative |")
    p("|---|---|---|---|---|---|")
    cum = STARTING_RM + PROLOGUE_BOUNTY
    p(f"| 0 | Prologue | gold transport | {PROLOGUE_BOUNTY} | – | {cum} |")
    kill_total = 0
    breach_total = 0
    for i, (name, groups) in enumerate(WAVES, 1):
        kills = sum(ENEMIES[k]["bounty"] * n for k, n in groups)
        breach_total += sum(ENEMIES[k]["breach"] * n for k, n in groups)
        kill_total += kills
        cum += kills + WAVE_CLEAR_BONUS
        comp = ", ".join(f"{n} {k}" for k, n in groups)
        p(f"| {i} | {name} | {comp} | {kills} | {WAVE_CLEAR_BONUS} | {cum} |")
    income = cum
    p("")
    p(f"Perfect-run income: **{income} RM** = prologue {PROLOGUE_BOUNTY} + kills {kill_total} + "
      f"bonuses {WAVE_CLEAR_BONUS * len(WAVES)}.\n")

    # ---- checks -------------------------------------------------------------
    p("## Checks\n")
    checks = []
    ratio = income / everything
    checks.append((abs(ratio - ECONOMY_TARGET) <= 0.03,
                   f"economy target: income / everything = {ratio:.2f} (target {ECONOMY_TARGET:.2f})"))
    boat_ratio = boat_max / (boat_max + turret_max * ratio)
    checks.append((0.40 <= boat_ratio <= 0.55,
                   f"boat share of an affordable budget = {boat_ratio:.2f} (target ≈ {BOAT_SHARE:.2f})"))
    avg_turret = turret_max / sum(REFERENCE_BUILD.values())
    checks.append((3 * avg_turret <= boat_max <= 4.5 * avg_turret,
                   f"boat maxed = {boat_max / avg_turret:.1f} maxed turrets (target 3–4)"))
    flak = TURRETS["flak"]["cost"][0]
    checks.append((2 * flak <= PROLOGUE_BOUNTY < 3 * flak,
                   f"prologue bounty {PROLOGUE_BOUNTY} buys two flak ({2 * flak}) but not three"))
    # affordability of boat models on a boat-first plan: one flak in wave 1, rest saved
    cum_by_wave = [STARTING_RM + PROLOGUE_BOUNTY]
    for _, groups in WAVES:
        cum_by_wave.append(cum_by_wave[-1] + sum(ENEMIES[k]["bounty"] * n for k, n in groups)
                           + WAVE_CLEAR_BONUS)
    saved = [c - flak for c in cum_by_wave]
    for b in BOATS[1:]:
        need = sum(x["price"] for x in BOATS[1:BOATS.index(b) + 1])
        wave_ok = next((w for w, s in enumerate(saved) if s >= need), None)
        checks.append((wave_ok is not None and wave_ok <= b["unlock"] + 1,
                       f"boat-first plan affords {b['name']} after wave {wave_ok} (unlock {b['unlock']})"))
    checks.append((breach_total > STARTING_INTEGRITY * 3,
                   f"breach damage of all waves = {breach_total} vs integrity {STARTING_INTEGRITY} "
                   f"(a leaky defence must be able to lose)"))
    for ok, text in checks:
        p(f"- {'OK ' if ok else 'FAIL'} {text}")
    p("")

    # ---- threat → answer ----------------------------------------------------
    p("## Threat → answer, numerically\n")
    p("Sustained: kills per 10 s of a continuous stream by one tier-1 turret (damage after armour × "
      "shots per 10 s ÷ HP). Per RM: the same per 100 RM of build cost — this is what separates the "
      "roles, because turn rate and reload make the 15 cm slow to start and the flak cheap. "
      "Torpedoes: per kill. Deck gun: kills per 10 s.\n")
    p("| Enemy | HP / armour | flak | per RM | 8.8 | per RM | 8.8 AP | 15cm | per RM | torpedoes VIIA / VIIC / IXC | deck gun |")
    p("|---|---|---|---|---|---|---|---|---|---|---|")
    for e, d in ENEMIES.items():
        cells = []
        for t, td in TURRETS.items():
            per10 = 10.0 / td["reload"] * hit(td["damage"], d["armour"]) / d["hp"]
            cells.append(f"{per10:.2f}")
            cells.append(f"{per10 / (td['cost'][0] / 100):.2f}")
            if t == "8.8":
                cells.append(f"{10.0 / td['reload'] * hit(td['damage'], d['armour'], ap=True) / d['hp']:.2f}")
        torps = " / ".join(str(int(-(-d["hp"] // b["torpedo"]))) for b in BOATS)
        gun = 10.0 / DECK_GUN["reload"] * hit(DECK_GUN["damage"], d["armour"]) / d["hp"]
        p(f"| {e} | {d['hp']:.0f} / {d['armour']:.0f} | {' | '.join(cells)} | {torps} | {gun:.2f} |")
    g = GOLD_TRANSPORT
    p(f"| Gold transport (prologue) | {g['hp']:.0f} / {g['armour']:.0f} | – | – | – | – | – | – | – | "
      f"{' / '.join(str(int(-(-g['hp'] // b['torpedo']))) for b in BOATS)} | "
      f"{10.0 / DECK_GUN['reload'] * DECK_GUN['damage'] / g['hp']:.2f} |")
    p("")
    p("Expected from `enemies.md`: flak best per RM vs MTB and useless (< 0.1) vs Destroyer; 8.8 the "
      "best per RM vs Corvette; 8.8 AP still clearly below 15cm vs Destroyer; 15cm kills a Destroyer "
      "slowly (a single one needs several passes); Monitor: every gun < 0.1, one IXC sortie (8 tubes) "
      "kills it; three VIIA torpedoes kill a Destroyer with one tube spare (no 10-HP leftovers).\n")

    # ---- boat survival ------------------------------------------------------
    p("## Boat under destroyer fire\n")
    s = DESTROYER_SHELLING
    for b in BOATS:
        hits = -(-b["hp"] // s["damage"])
        secs = s["ranging"] + (hits - 1) * s["reload"]
        p(f"- {b['name']}: dies after {hits:.0f} hits ≈ {secs:.1f} s surfaced inside one destroyer's "
          f"range; a salvo of {b['tubes']} tubes takes ≈ {0.3 * (b['tubes'] - 1) + 0.3:.1f} s")
    p("")
    p("Ramming, fraction of boat max HP: passive collision light "
      f"{RAM['passive_light']:.0%}, passive heavy {RAM['passive_heavy']:.0%}, active ram light "
      f"{RAM['active_light']:.0%}. Torpedo run {TORPEDO_RUN_TILES:.0f} tiles; the longest straight "
      "must be longer.\n")

    print("\n".join(out))


if __name__ == "__main__":
    main()
